function build(board: 'cbse' | 'icse', cls: number, subjects: readonly StandardSubject[]) {
  return subjects.map((subject, position): StandardCatalogSubject => {
    const books = subject.books ?? [{ book: undefined, chapters: subject.chapters }];
    return {
      board,
      cls,
      subjectId: subject.id,
      name: subject.name,
      color: COLORS[subject.id] ?? '#007AFF',
      position,
      chapters: books.flatMap(({ book, chapters }) =>
        chapters.map((chapter) => {
          const [name, difficulty] = typeof chapter === 'string' ? [chapter, 2 as const] : chapter;
          return book ? { name, difficulty, book } : { name, difficulty };
        }),
      ),
    };
  });
}

/** Every standard subject of CBSE and ICSE, classes 6 to 12. */
export function standardSubjects(): StandardCatalogSubject[] {
  const classes = [6, 7, 8, 9, 10, 11, 12];
  return [
    ...classes.flatMap((cls) => build('cbse', cls, CBSE[cls] ?? [])),
    ...classes.flatMap((cls) => build('icse', cls, ICSE[cls] ?? [])),
  ];
}
