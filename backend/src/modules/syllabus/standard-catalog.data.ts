/**
 * The standard CBSE and ICSE/ISC syllabus for classes 6 to 12: every subject a student
 * usually studies, with its chapters in book order.
 *
 * - CBSE (standard-catalog.cbse.ts) follows the current NCERT textbooks, chapter by chapter
 *   under each book, so Part 1 and Part 2 of a book sit in the same subject as two books. Classes 6–8 use the new NCF-2023 books
 *   (Ganita Prakash, Curiosity, Exploring Society, Poorvi, Malhar); classes 9–10 keep the
 *   NCERT data that first shipped with the app (see `SYLLABUS`); classes 11–12 use the
 *   rationalised NCERT books.
 * - ICSE (classes 6–10) and ISC (classes 11–12) prescribe a syllabus, not one textbook, so
 *   chapters follow the CISCE syllabus topics in the order the common textbooks teach them.
 *   Language subjects are split by paper/skill because the literature texts vary by school.
 *
 * A fresh install loads all of this. Existing installs load it from the admin portal
 * ("Load standard syllabus"), which adds missing subjects, chapters and book names but keeps
 * admin edits (see CatalogService.importStandard).
 * Difficulty is 1 easy, 2 medium (the default when a chapter is a plain string), 3 hard.
 */
