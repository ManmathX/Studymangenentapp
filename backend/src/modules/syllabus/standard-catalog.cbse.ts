/**
 * CBSE classes 6–12, following the current NCERT textbooks. Each subject lists its books in
 * order (Part 1 before Part 2, main reader before supplementary reader), and each book its
 * chapters in book order. Classes 9 and 10 reuse the NCERT data the app shipped with (see
 * `SYLLABUS`), split into books, so chapter order there never changes.
 */
import type { Chapter, StandardSubject } from './standard-catalog.types.js';
import { SYLLABUS } from './syllabus.data.js';

const book = (name: string, chapters: readonly Chapter[]) => ({ book: name, chapters });

/** Splits one of the shipped class 9/10 chapter lists into books by chapter count. */
function shipped(
  cls: 9 | 10,
  subject: keyof (typeof SYLLABUS)[9],
  splits: readonly (readonly [book: string, count: number])[],
) {
  const all = SYLLABUS[cls][subject];
  let start = 0;
  return splits.map(([name, count]) => {
    const chapters = all.slice(start, start + count);
    start += count;
    return book(name, chapters);
  });
}

